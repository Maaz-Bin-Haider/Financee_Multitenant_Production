CREATE OR REPLACE VIEW chartofaccounts AS SELECT * FROM chart_of_accounts;
CREATE OR REPLACE VIEW journalentries AS SELECT journal_id,entry_date AS journal_date,
 entry_date,description,source_document_type,source_document_id,
