CREATE TABLE IF NOT EXISTS parties(
 party_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 party_name varchar(200) NOT NULL UNIQUE,party_type varchar(20) NOT NULL,
 contact_info text,address text,opening_balance numeric(24,4) NOT NULL DEFAULT 0,
 balance_type varchar(6) NOT NULL DEFAULT 'Debit',
 ar_account_id bigint REFERENCES chart_of_accounts(account_id),
 ap_account_id bigint REFERENCES chart_of_accounts(account_id),
 expense_account_id bigint REFERENCES chart_of_accounts(account_id),
 opening_journal_id bigint UNIQUE REFERENCES journal_entries(journal_id),
 is_cash boolean NOT NULL DEFAULT false,is_active boolean NOT NULL DEFAULT true,
 created_by integer,created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(btrim(party_name)<>''),CHECK(party_type IN('Customer','Vendor','Both','Expense')),
 CHECK(opening_balance>=0),CHECK(balance_type IN('Debit','Credit')));
ALTER TABLE journal_lines DROP CONSTRAINT IF EXISTS journal_lines_party_id_fkey;
ALTER TABLE journal_lines ADD CONSTRAINT journal_lines_party_id_fkey FOREIGN KEY(party_id) REFERENCES parties(party_id);

CREATE TABLE IF NOT EXISTS payments(
 payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,payment_date date NOT NULL,
 party_id bigint NOT NULL REFERENCES parties(party_id),amount numeric(24,4) NOT NULL,
 method varchar(20) NOT NULL DEFAULT 'Cash',reference_no varchar(100),description text,
 journal_id bigint NOT NULL UNIQUE REFERENCES journal_entries(journal_id),
 status varchar(10) NOT NULL DEFAULT 'posted',created_by integer,created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(amount>0),CHECK(method IN('Cash','Bank','Cheque','Online')),CHECK(status IN('posted','reversed')));
CREATE TABLE IF NOT EXISTS receipts(
 receipt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,receipt_date date NOT NULL,
 party_id bigint NOT NULL REFERENCES parties(party_id),amount numeric(24,4) NOT NULL,
 method varchar(20) NOT NULL DEFAULT 'Cash',reference_no varchar(100),description text,
 journal_id bigint NOT NULL UNIQUE REFERENCES journal_entries(journal_id),
 status varchar(10) NOT NULL DEFAULT 'posted',created_by integer,created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(amount>0),CHECK(method IN('Cash','Bank','Cheque','Online')),CHECK(status IN('posted','reversed')));
CREATE TABLE IF NOT EXISTS contra_entries(
 contra_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,contra_date date NOT NULL,
 from_party_id bigint NOT NULL REFERENCES parties(party_id),to_party_id bigint NOT NULL REFERENCES parties(party_id),
 amount numeric(24,4) NOT NULL,method varchar(20) NOT NULL DEFAULT 'Cash',
 reference_no varchar(100),description text,journal_id bigint NOT NULL UNIQUE REFERENCES journal_entries(journal_id),
 status varchar(10) NOT NULL DEFAULT 'posted',created_by integer,created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(from_party_id<>to_party_id),CHECK(amount>0),CHECK(status IN('posted','reversed')));
CREATE TABLE IF NOT EXISTS opening_cash(
 opening_cash_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,amount numeric(24,4) NOT NULL DEFAULT 0,
 journal_id bigint UNIQUE REFERENCES journal_entries(journal_id),created_by integer,updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(amount>=0));
CREATE TABLE IF NOT EXISTS owner_equity_transactions(
 txn_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,txn_date date NOT NULL,
 direction varchar(12) NOT NULL,amount numeric(24,4) NOT NULL,
 equity_account_id bigint NOT NULL REFERENCES chart_of_accounts(account_id),description text,
 journal_id bigint NOT NULL UNIQUE REFERENCES journal_entries(journal_id),
 status varchar(10) NOT NULL DEFAULT 'posted',created_by integer,created_at timestamptz NOT NULL DEFAULT now(),
 CHECK(direction IN('injection','withdrawal')),CHECK(amount>0),CHECK(status IN('posted','reversed')));
CREATE TABLE IF NOT EXISTS period_closes(
 period_close_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 period_year integer NOT NULL,period_month integer NOT NULL,closed_at timestamptz NOT NULL DEFAULT now(),
 closed_by integer,UNIQUE(period_year,period_month),CHECK(period_year BETWEEN 2000 AND 9999),
 CHECK(period_month BETWEEN 1 AND 12));

CREATE OR REPLACE FUNCTION quantity_assert_open_date(p_date date) RETURNS void LANGUAGE plpgsql STABLE AS $$
BEGIN
 IF p_date IS NULL THEN RAISE EXCEPTION 'Transaction date is required.'; END IF;
 IF EXISTS(SELECT 1 FROM period_closes WHERE period_year=extract(year FROM p_date)
 AND period_month=extract(month FROM p_date)) THEN
  RAISE EXCEPTION 'Accounting period is closed for %.',p_date USING ERRCODE='check_violation';
 END IF;
END $$;
CREATE OR REPLACE FUNCTION quantity_period_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d date;r jsonb;k text;
BEGIN
 IF current_setting('financee.period_close_admin',true)='allowed' THEN RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END; END IF;
 IF TG_OP='DELETE' THEN r:=to_jsonb(OLD);ELSE r:=to_jsonb(NEW);END IF;
 k:=CASE TG_TABLE_NAME WHEN 'journal_entries' THEN 'entry_date'
 WHEN 'warehouse_transfers' THEN 'transfer_date' WHEN 'physical_counts' THEN 'count_date'
 WHEN 'opening_stock_documents' THEN 'opening_date' END;
 d:=(r->>k)::date;
 PERFORM quantity_assert_open_date(d);RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
END $$;
DROP TRIGGER IF EXISTS quantity_period_journal_guard ON journal_entries;
CREATE TRIGGER quantity_period_journal_guard BEFORE INSERT OR UPDATE OR DELETE ON journal_entries FOR EACH ROW EXECUTE FUNCTION quantity_period_guard();
DROP TRIGGER IF EXISTS quantity_period_transfer_guard ON warehouse_transfers;
CREATE TRIGGER quantity_period_transfer_guard BEFORE INSERT OR UPDATE OR DELETE ON warehouse_transfers FOR EACH ROW EXECUTE FUNCTION quantity_period_guard();
DROP TRIGGER IF EXISTS quantity_period_count_guard ON physical_counts;
CREATE TRIGGER quantity_period_count_guard BEFORE INSERT OR UPDATE OR DELETE ON physical_counts FOR EACH ROW EXECUTE FUNCTION quantity_period_guard();
DROP TRIGGER IF EXISTS quantity_period_opening_guard ON opening_stock_documents;
CREATE TRIGGER quantity_period_opening_guard BEFORE INSERT OR UPDATE OR DELETE ON opening_stock_documents FOR EACH ROW EXECUTE FUNCTION quantity_period_guard();

CREATE OR REPLACE FUNCTION add_party_from_json(data jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE id bigint;nm text;typ text;amt numeric;bt text;usr integer;j bigint;ar bigint;ap bigint;exp bigint;code text;
BEGIN
 nm:=upper(btrim(COALESCE(data->>'party_name','')));typ:=data->>'party_type';
 amt:=COALESCE(NULLIF(data->>'opening_balance','')::numeric,0);bt:=COALESCE(NULLIF(data->>'balance_type',''),'Debit');
 usr:=NULLIF(data->>'created_by_id','')::integer;
 IF nm='' OR typ NOT IN('Customer','Vendor','Both','Expense') OR amt<0 OR bt NOT IN('Debit','Credit')
 THEN RAISE EXCEPTION 'Party values are invalid.' USING ERRCODE='check_violation'; END IF;
 SELECT account_id INTO ar FROM chart_of_accounts WHERE account_code='1200';
 SELECT account_id INTO ap FROM chart_of_accounts WHERE account_code='2000';
 IF typ='Expense' THEN
  code:='E'||lpad(nextval('parties_party_id_seq')::text,10,'0');
  INSERT INTO chart_of_accounts(account_code,account_name,account_type,normal_balance,is_system)
  VALUES(code,nm,'Expense','Debit',false) RETURNING account_id INTO exp;
  INSERT INTO parties(party_id,party_name,party_type,contact_info,address,opening_balance,balance_type,expense_account_id,created_by)
  VALUES(currval('parties_party_id_seq'),nm,typ,data->>'contact_info',data->>'address',amt,bt,exp,usr) RETURNING party_id INTO id;
 ELSE
  INSERT INTO parties(party_name,party_type,contact_info,address,opening_balance,balance_type,ar_account_id,ap_account_id,created_by)
  VALUES(nm,typ,data->>'contact_info',data->>'address',amt,bt,
  CASE WHEN typ IN('Customer','Both') THEN ar END,CASE WHEN typ IN('Vendor','Both') THEN ap END,usr)
  RETURNING party_id INTO id;
 END IF;
 IF amt>0 THEN
  j:=quantity_post_journal(CURRENT_DATE,'Party opening balance','party_opening',id,nm,usr,
  jsonb_build_array(jsonb_build_object('account_code',CASE WHEN typ='Expense' THEN code
  WHEN typ='Vendor' OR (typ='Both' AND bt='Credit') THEN '2000' ELSE '1200' END,
  'party_id',id,'debit',CASE WHEN bt='Debit' THEN amt ELSE 0 END,'credit',CASE WHEN bt='Credit' THEN amt ELSE 0 END),
  jsonb_build_object('account_code','3001','debit',CASE WHEN bt='Credit' THEN amt ELSE 0 END,
  'credit',CASE WHEN bt='Debit' THEN amt ELSE 0 END)));
  UPDATE parties SET opening_journal_id=j WHERE party_id=id;
 END IF;
 RETURN jsonb_build_object('status','success','party_id',id,'party_name',nm);
END $$;

CREATE OR REPLACE FUNCTION update_party_from_json(p_id bigint,data jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE p parties%ROWTYPE;nm text;amt numeric;bt text;usr integer;j bigint;party_code text;
BEGIN SELECT * INTO p FROM parties WHERE party_id=p_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Party not found.'; END IF;
 nm:=upper(btrim(COALESCE(NULLIF(data->>'party_name',''),p.party_name)));
 amt:=COALESCE(NULLIF(data->>'opening_balance','')::numeric,p.opening_balance);
 bt:=COALESCE(NULLIF(data->>'balance_type',''),p.balance_type);usr:=NULLIF(data->>'created_by_id','')::integer;
 IF p.opening_journal_id IS NOT NULL THEN PERFORM quantity_reverse_journal(p.opening_journal_id,CURRENT_DATE,'Revise party opening',usr); END IF;
 j:=NULL;
 IF p.party_type='Expense' THEN SELECT account_code INTO party_code FROM chart_of_accounts WHERE account_id=p.expense_account_id;
 ELSIF p.party_type='Vendor' OR (p.party_type='Both' AND bt='Credit') THEN party_code:='2000';ELSE party_code:='1200';END IF;
 IF amt>0 THEN j:=quantity_post_journal(CURRENT_DATE,'Party opening balance','party_opening_revision',p_id,nm,usr,
 jsonb_build_array(jsonb_build_object('account_code',party_code,
 'party_id',p_id,'debit',CASE WHEN bt='Debit' THEN amt ELSE 0 END,'credit',CASE WHEN bt='Credit' THEN amt ELSE 0 END),
 jsonb_build_object('account_code','3001','debit',CASE WHEN bt='Credit' THEN amt ELSE 0 END,
 'credit',CASE WHEN bt='Debit' THEN amt ELSE 0 END))); END IF;
 UPDATE parties SET party_name=nm,contact_info=COALESCE(data->>'contact_info',contact_info),
 address=COALESCE(data->>'address',address),opening_balance=amt,balance_type=bt,
 opening_journal_id=j,updated_at=now() WHERE party_id=p_id;
 RETURN jsonb_build_object('status','success','party_id',p_id,'party_name',nm);
END $$;

