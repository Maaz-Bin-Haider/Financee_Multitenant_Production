CREATE OR REPLACE FUNCTION make_payment(data jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE id bigint;p parties%ROWTYPE;amt numeric;d date;m text;j bigint;usr integer;
BEGIN SELECT * INTO p FROM parties WHERE upper(party_name)=upper(data->>'party_name');
 amt:=(data->>'amount')::numeric;d:=COALESCE(NULLIF(data->>'payment_date','')::date,CURRENT_DATE);
 m:=COALESCE(NULLIF(data->>'method',''),'Cash');usr:=NULLIF(data->>'created_by_id','')::integer;
 IF NOT FOUND OR amt<=0 THEN RAISE EXCEPTION 'Payment party or amount is invalid.' USING ERRCODE='check_violation'; END IF;
 id:=nextval('payments_payment_id_seq');
 j:=quantity_post_journal(d,'Payment to '||p.party_name,'payment',id,data->>'reference_no',usr,
 jsonb_build_array(jsonb_build_object('account_code','2000','party_id',p.party_id,'debit',amt,'credit',0),
 jsonb_build_object('account_code',quantity_cash_account(m),'debit',0,'credit',amt)));
 INSERT INTO payments(payment_id,payment_date,party_id,amount,method,reference_no,description,journal_id,created_by)
 VALUES(id,d,p.party_id,amt,m,data->>'reference_no',data->>'description',j,usr);
 RETURN jsonb_build_object('status','success','payment_id',id,'journal_id',j);END $$;
