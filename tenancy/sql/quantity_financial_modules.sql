CREATE OR REPLACE FUNCTION make_contra(data jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE id bigint;fp parties%ROWTYPE;tp parties%ROWTYPE;amt numeric;d date;j bigint;usr integer;
BEGIN SELECT * INTO fp FROM parties WHERE upper(party_name)=upper(data->>'from_party_name');
 SELECT * INTO tp FROM parties WHERE upper(party_name)=upper(data->>'to_party_name');
 amt:=(data->>'amount')::numeric;d:=COALESCE(NULLIF(data->>'contra_date','')::date,CURRENT_DATE);
 usr:=NULLIF(data->>'created_by_id','')::integer;
 IF fp.party_id IS NULL OR tp.party_id IS NULL OR fp.party_id=tp.party_id THEN
 RAISE EXCEPTION 'Contra parties cannot be the same or missing.' USING ERRCODE='check_violation'; END IF;
 IF amt<=0 THEN RAISE EXCEPTION 'Contra amount is invalid.' USING ERRCODE='check_violation'; END IF;
 id:=nextval('contra_entries_contra_id_seq');
 j:=quantity_post_journal(d,'Contra '||fp.party_name||' to '||tp.party_name,'contra',id,data->>'reference_no',usr,
 jsonb_build_array(jsonb_build_object('account_code','1200','party_id',tp.party_id,'debit',amt,'credit',0),
 jsonb_build_object('account_code','1200','party_id',fp.party_id,'debit',0,'credit',amt)));
 INSERT INTO contra_entries(contra_id,contra_date,from_party_id,to_party_id,amount,reference_no,description,journal_id,created_by)
 VALUES(id,d,fp.party_id,tp.party_id,amt,data->>'reference_no',data->>'description',j,usr);
 RETURN jsonb_build_object('status','success','contra_id',id,'journal_id',j);END $$;

CREATE OR REPLACE FUNCTION quantity_reverse_financial(p_kind text,p_id bigint) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE j bigint;d date;usr integer;
BEGIN
 IF p_kind='payment' THEN SELECT journal_id,payment_date,created_by INTO j,d,usr FROM payments WHERE payment_id=p_id AND status='posted' FOR UPDATE;
 ELSIF p_kind='receipt' THEN SELECT journal_id,receipt_date,created_by INTO j,d,usr FROM receipts WHERE receipt_id=p_id AND status='posted' FOR UPDATE;
 ELSE SELECT journal_id,contra_date,created_by INTO j,d,usr FROM contra_entries WHERE contra_id=p_id AND status='posted' FOR UPDATE; END IF;
 IF j IS NULL THEN RAISE EXCEPTION 'Financial document not found.'; END IF;
 PERFORM quantity_reverse_journal(j,d,'Reverse '||p_kind,usr);
 IF p_kind='payment' THEN UPDATE payments SET status='reversed' WHERE payment_id=p_id;
 ELSIF p_kind='receipt' THEN UPDATE receipts SET status='reversed' WHERE receipt_id=p_id;
 ELSE UPDATE contra_entries SET status='reversed' WHERE contra_id=p_id; END IF;
 RETURN jsonb_build_object('status','success','id',p_id);END $$;
