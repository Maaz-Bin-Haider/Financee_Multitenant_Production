CREATE OR REPLACE FUNCTION get_party_balance_by_name(p_name text) RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT COALESCE((SELECT jsonb_build_object('found',true,'party_id',p.party_id,'party_name',p.party_name,
 'party_type',p.party_type,'balance',COALESCE(sum(jl.debit-jl.credit),0))
 FROM parties p LEFT JOIN journal_lines jl ON jl.party_id=p.party_id WHERE upper(p.party_name)=upper(p_name)
 GROUP BY p.party_id),jsonb_build_object('found',false,'party_name',p_name)) $$;
CREATE OR REPLACE FUNCTION get_party_balances_json() RETURNS jsonb LANGUAGE sql STABLE AS $$
