CREATE OR REPLACE FUNCTION set_opening_cash_from_json(data jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE amt numeric;old opening_cash%ROWTYPE;j bigint;usr integer;
BEGIN amt:=(data->>'amount')::numeric;usr:=NULLIF(data->>'created_by_id','')::integer;
 IF amt<0 THEN RAISE EXCEPTION 'Opening cash cannot be negative.' USING ERRCODE='check_violation'; END IF;
 SELECT * INTO old FROM opening_cash LIMIT 1 FOR UPDATE;
 IF FOUND AND old.journal_id IS NOT NULL THEN PERFORM quantity_reverse_journal(old.journal_id,CURRENT_DATE,'Revise opening cash',usr); END IF;
 j:=NULL;
 IF amt>0 THEN j:=quantity_post_journal(CURRENT_DATE,'Opening Cash in Hand','opening_cash',
 COALESCE(old.opening_cash_id,1),NULL,usr,jsonb_build_array(
 jsonb_build_object('account_code','1000','debit',amt,'credit',0),
 jsonb_build_object('account_code','3000','debit',0,'credit',amt))); END IF;
 IF old.opening_cash_id IS NULL THEN INSERT INTO opening_cash(amount,journal_id,created_by) VALUES(amt,j,usr);
 ELSE UPDATE opening_cash SET amount=amt,journal_id=j,created_by=usr,updated_at=now(); END IF;
 RETURN jsonb_build_object('status','success','amount',amt,'journal_id',j);END $$;

CREATE OR REPLACE FUNCTION add_owner_equity_txn(data jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE id bigint;dir text;amt numeric;d date;acct chart_of_accounts%ROWTYPE;j bigint;usr integer;
BEGIN dir:=data->>'direction';amt:=(data->>'amount')::numeric;
 d:=COALESCE(NULLIF(data->>'txn_date','')::date,CURRENT_DATE);usr:=NULLIF(data->>'created_by_id','')::integer;
 IF dir NOT IN('injection','withdrawal') THEN RAISE EXCEPTION 'Invalid direction.' USING ERRCODE='check_violation'; END IF;
 IF amt<=0 THEN RAISE EXCEPTION 'Invalid amount.' USING ERRCODE='check_violation'; END IF;
 SELECT * INTO acct FROM chart_of_accounts WHERE account_type='Equity' AND account_name=
 COALESCE(NULLIF(data->>'equity_account',''),'Owner''s Capital');
 IF NOT FOUND THEN RAISE EXCEPTION 'Equity account not found.'; END IF;
 id:=nextval('owner_equity_transactions_txn_id_seq');
 j:=quantity_post_journal(d,'Owner equity '||dir,'owner_equity',id,NULL,usr,
 jsonb_build_array(jsonb_build_object('account_code','1000',
 'debit',CASE WHEN dir='injection' THEN amt ELSE 0 END,'credit',CASE WHEN dir='withdrawal' THEN amt ELSE 0 END),
 jsonb_build_object('account_code',acct.account_code,'debit',CASE WHEN dir='withdrawal' THEN amt ELSE 0 END,
 'credit',CASE WHEN dir='injection' THEN amt ELSE 0 END)));
 INSERT INTO owner_equity_transactions(txn_id,txn_date,direction,amount,equity_account_id,description,journal_id,created_by)
 VALUES(id,d,dir,amt,acct.account_id,data->>'description',j,usr);
 RETURN jsonb_build_object('status','success','txn_id',id,'journal_id',j);END $$;
CREATE OR REPLACE FUNCTION delete_owner_equity_txn(p_id bigint) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE x owner_equity_transactions%ROWTYPE;
BEGIN SELECT * INTO x FROM owner_equity_transactions WHERE txn_id=p_id AND status='posted' FOR UPDATE;
 IF NOT FOUND THEN RETURN jsonb_build_object('status','not_found'); END IF;
 PERFORM quantity_reverse_journal(x.journal_id,x.txn_date,'Reverse owner equity',x.created_by);
 UPDATE owner_equity_transactions SET status='reversed' WHERE txn_id=p_id;
 RETURN jsonb_build_object('status','success','txn_id',p_id);END $$;
CREATE OR REPLACE FUNCTION get_owner_equity_json(p_limit integer) RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT jsonb_build_object('transactions',COALESCE(jsonb_agg(to_jsonb(x) ORDER BY txn_id DESC),'[]'::jsonb))
 FROM(SELECT o.*,c.account_name equity_account FROM owner_equity_transactions o
 JOIN chart_of_accounts c ON c.account_id=o.equity_account_id ORDER BY txn_id DESC LIMIT p_limit)x $$;

CREATE OR REPLACE FUNCTION preview_period_close(p_year integer,p_month integer) RETURNS jsonb LANGUAGE plpgsql STABLE AS $$
DECLARE sd date;ed date;
BEGIN IF p_month NOT BETWEEN 1 AND 12 THEN RAISE EXCEPTION 'Invalid month.'; END IF;
 sd:=make_date(p_year,p_month,1);ed:=(sd+interval '1 month - 1 day')::date;
 RETURN jsonb_build_object('year',p_year,'month',p_month,'start_date',sd,'end_date',ed,
 'debit_total',(SELECT COALESCE(sum(debit),0) FROM journal_lines l JOIN journal_entries e USING(journal_id) WHERE e.entry_date BETWEEN sd AND ed),
 'credit_total',(SELECT COALESCE(sum(credit),0) FROM journal_lines l JOIN journal_entries e USING(journal_id) WHERE e.entry_date BETWEEN sd AND ed),
 'is_closed',EXISTS(SELECT 1 FROM period_closes WHERE period_year=p_year AND period_month=p_month));END $$;
CREATE OR REPLACE FUNCTION close_period_from_json(data jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE y integer;m integer;usr integer;
BEGIN y:=(data->>'year')::integer;m:=(data->>'month')::integer;usr:=NULLIF(data->>'created_by_id','')::integer;
 IF m NOT BETWEEN 1 AND 12 THEN RAISE EXCEPTION 'Invalid month.'; END IF;
 IF EXISTS(SELECT 1 FROM period_closes WHERE period_year=y AND period_month=m) THEN RAISE EXCEPTION 'Period is already closed.'; END IF;
 INSERT INTO period_closes(period_year,period_month,closed_by) VALUES(y,m,usr);
 RETURN jsonb_build_object('status','success','year',y,'month',m);END $$;
CREATE OR REPLACE FUNCTION reverse_period_close(p_year integer,p_month integer) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE removed integer;
BEGIN PERFORM set_config('financee.period_close_admin','allowed',true);
 DELETE FROM period_closes WHERE period_year=p_year AND period_month=p_month;GET DIAGNOSTICS removed=ROW_COUNT;
 PERFORM set_config('financee.period_close_admin','',true);
 IF removed=0 THEN RETURN jsonb_build_object('status','not_found'); END IF;
 RETURN jsonb_build_object('status','success','year',p_year,'month',p_month);END $$;
CREATE OR REPLACE FUNCTION get_period_closes_json() RETURNS jsonb LANGUAGE sql STABLE AS $$
 SELECT jsonb_build_object('closed',COALESCE(jsonb_agg(to_jsonb(p) ORDER BY period_year DESC,period_month DESC),'[]'::jsonb))
 FROM period_closes p $$;
CREATE OR REPLACE FUNCTION reclassify_opening_balance_to_capital(data jsonb) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE bal numeric;j bigint;usr integer;
BEGIN SELECT COALESCE(sum(l.credit-l.debit),0) INTO bal FROM journal_lines l JOIN chart_of_accounts c USING(account_id) WHERE c.account_code='3001';
 IF bal=0 THEN RETURN jsonb_build_object('status','noop','amount',0); END IF;
 usr:=NULLIF(data->>'created_by_id','')::integer;
 j:=quantity_post_journal(CURRENT_DATE,'Reclassify Opening Balance','opening_reclass',NULL,NULL,usr,
 jsonb_build_array(jsonb_build_object('account_code',CASE WHEN bal>0 THEN '3001' ELSE '3000' END,'debit',abs(bal),'credit',0),
 jsonb_build_object('account_code',CASE WHEN bal>0 THEN '3000' ELSE '3001' END,'debit',0,'credit',abs(bal))));
 RETURN jsonb_build_object('status','success','amount',abs(bal),'journal_id',j);END $$;

