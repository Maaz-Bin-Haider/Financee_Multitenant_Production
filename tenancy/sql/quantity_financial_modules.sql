BEGIN SELECT * INTO p FROM parties WHERE upper(party_name)=upper(data->>'party_name');
 amt:=(data->>'amount')::numeric;d:=COALESCE(NULLIF(data->>'receipt_date','')::date,CURRENT_DATE);
 m:=COALESCE(NULLIF(data->>'method',''),'Cash');usr:=NULLIF(data->>'created_by_id','')::integer;
