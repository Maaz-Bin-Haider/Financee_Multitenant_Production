DECLARE old payments%ROWTYPE;r jsonb;BEGIN SELECT * INTO old FROM payments WHERE payment_id=p_id AND status='posted';
 IF NOT FOUND THEN RAISE EXCEPTION 'Payment not found.'; END IF;PERFORM quantity_reverse_financial('payment',p_id);
 data:=data||jsonb_build_object('party_name',(SELECT party_name FROM parties WHERE party_id=old.party_id),
 'payment_date',COALESCE(data->>'payment_date',old.payment_date::text),'method',COALESCE(data->>'method',old.method),
 'created_by_id',old.created_by);r:=make_payment(data);RETURN r||jsonb_build_object('replaced_payment_id',p_id);END $$;
