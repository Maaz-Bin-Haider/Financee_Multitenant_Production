            USING ERRCODE = 'foreign_key_violation';
    END IF;
    RETURN p_variant_id;
END;
$$;

CREATE OR REPLACE FUNCTION quantity_item_catalog(
    search_text text DEFAULT NULL, active_only boolean DEFAULT true
) RETURNS TABLE (
    product_id bigint, product_name varchar, category varchar,
    variant_id bigint, sku varchar, brand varchar, model varchar,
    color varchar, storage varchar, ram varchar, region varchar,
    condition varchar, unit_code varchar, unit_name varchar,
    quantity_scale smallint, reorder_level numeric, is_active boolean
) LANGUAGE sql STABLE AS $$
    SELECT p.product_id, p.product_name, p.category, v.variant_id, v.sku,
           v.brand, v.model, v.color, v.storage, v.ram, v.region, v.condition,
           u.code, u.unit_name, u.quantity_scale, v.reorder_level,
           (p.is_active AND v.is_active AND u.is_active)
      FROM products p
      JOIN product_variants v ON v.product_id = p.product_id
      JOIN units_of_measure u ON u.unit_id = v.unit_id
     WHERE (NOT active_only OR (p.is_active AND v.is_active AND u.is_active))
       AND (search_text IS NULL OR btrim(search_text) = ''
            OR v.sku ILIKE '%' || search_text || '%'
            OR p.product_name ILIKE '%' || search_text || '%'
            OR v.brand ILIKE '%' || search_text || '%'
            OR v.model ILIKE '%' || search_text || '%')
     ORDER BY p.product_name, v.sku;
$$;

