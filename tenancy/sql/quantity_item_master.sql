CREATE OR REPLACE FUNCTION quantity_normalize_sku_token(value text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT trim(both '-' FROM regexp_replace(
        upper(COALESCE(value, '')), '[^A-Z0-9]+', '-', 'g'
    ));
$$;

CREATE OR REPLACE FUNCTION quantity_suggest_sku(
    p_product_name text, p_brand text, p_model text, p_color text,
    p_storage text, p_ram text, p_region text, p_condition text
) RETURNS text LANGUAGE plpgsql AS $$
DECLARE
    base_sku text;
    candidate text;
    suffix integer := 1;
BEGIN
    base_sku := left(concat_ws('-',
        quantity_normalize_sku_token(p_product_name),
        quantity_normalize_sku_token(p_brand),
        quantity_normalize_sku_token(p_model),
        quantity_normalize_sku_token(p_color),
        quantity_normalize_sku_token(p_storage),
        quantity_normalize_sku_token(p_ram),
        quantity_normalize_sku_token(p_region),
        quantity_normalize_sku_token(p_condition)
    ), 56);
    IF base_sku = '' THEN
        RAISE EXCEPTION 'SKU source values are required.'
            USING ERRCODE = 'check_violation';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended(base_sku, 7307));
    candidate := base_sku;
    WHILE EXISTS (
        SELECT 1 FROM product_variants
         WHERE normalized_sku = upper(candidate)
    ) LOOP
        suffix := suffix + 1;
        candidate := left(base_sku, 64 - length(suffix::text) - 1)
                     || '-' || suffix::text;
    END LOOP;
    RETURN candidate;
END;
$$;

CREATE OR REPLACE FUNCTION quantity_validate_quantity(
    p_variant_id bigint, p_quantity numeric, p_allow_zero boolean DEFAULT false
) RETURNS void LANGUAGE plpgsql STABLE AS $$
DECLARE
    scale smallint;
BEGIN
    SELECT u.quantity_scale INTO scale
      FROM product_variants v
      JOIN units_of_measure u ON u.unit_id = v.unit_id
     WHERE v.variant_id = p_variant_id AND v.is_active AND u.is_active;
    IF scale IS NULL THEN
        RAISE EXCEPTION 'Unknown or inactive variant/unit.'
            USING ERRCODE = 'foreign_key_violation';
    END IF;
    IF p_quantity IS NULL OR p_quantity < 0
       OR (p_quantity = 0 AND NOT p_allow_zero)
       OR p_quantity <> round(p_quantity, scale)
       OR abs(p_quantity) >= 1000000000000000::numeric THEN
        RAISE EXCEPTION 'Quantity is invalid for the selected unit.'
            USING ERRCODE = 'check_violation';
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION quantity_variant_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM variant_transaction_registry
         WHERE variant_id = OLD.variant_id
    ) AND (
        upper(regexp_replace(btrim(NEW.sku), '\s+', '', 'g'))
            IS DISTINCT FROM OLD.normalized_sku
        OR NEW.unit_id IS DISTINCT FROM OLD.unit_id
    ) THEN
        RAISE EXCEPTION 'SKU and unit are locked after transactions exist.'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS product_variants_transaction_lock ON product_variants;
CREATE TRIGGER product_variants_transaction_lock
BEFORE UPDATE ON product_variants
FOR EACH ROW EXECUTE FUNCTION quantity_variant_guard();

CREATE OR REPLACE FUNCTION quantity_variant_precision_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    scale smallint;
BEGIN
    SELECT quantity_scale INTO scale FROM units_of_measure
     WHERE unit_id = NEW.unit_id AND is_active;
    IF scale IS NULL THEN
        RAISE EXCEPTION 'Unknown or inactive unit.'
            USING ERRCODE = 'foreign_key_violation';
    END IF;
    IF NEW.reorder_level <> round(NEW.reorder_level, scale) THEN
        RAISE EXCEPTION 'Reorder level is invalid for the selected unit.'
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS product_variants_precision ON product_variants;
CREATE TRIGGER product_variants_precision
BEFORE INSERT OR UPDATE OF unit_id, reorder_level ON product_variants
FOR EACH ROW EXECUTE FUNCTION quantity_variant_precision_guard();

CREATE OR REPLACE FUNCTION quantity_create_product(payload jsonb)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE
    new_id bigint;
BEGIN
    INSERT INTO products (
        product_name, category, description, created_by, updated_by
    ) VALUES (
        btrim(payload->>'product_name'), btrim(payload->>'category'),
        NULLIF(btrim(payload->>'description'), ''),
        (payload->>'user_id')::integer, (payload->>'user_id')::integer
    ) RETURNING product_id INTO new_id;
    RETURN new_id;
END;
$$;

CREATE OR REPLACE FUNCTION quantity_create_variant(payload jsonb)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE
    new_id bigint;
    selected_sku text;
    product_name text;
BEGIN
    SELECT p.product_name INTO product_name FROM products p
     WHERE p.product_id = (payload->>'product_id')::bigint AND p.is_active;
    IF product_name IS NULL THEN
        RAISE EXCEPTION 'Unknown or inactive product.'
            USING ERRCODE = 'foreign_key_violation';
    END IF;
    selected_sku := NULLIF(btrim(payload->>'sku'), '');
    IF selected_sku IS NULL THEN
        selected_sku := quantity_suggest_sku(
            product_name, payload->>'brand', payload->>'model',
            payload->>'color', payload->>'storage', payload->>'ram',
            payload->>'region', payload->>'condition'
        );
    END IF;
    INSERT INTO product_variants (
        product_id, sku, brand, model, color, storage, ram, region, condition,
        unit_id, reorder_level, created_by, updated_by
    ) VALUES (
        (payload->>'product_id')::bigint, selected_sku,
        btrim(payload->>'brand'), btrim(payload->>'model'),
        btrim(payload->>'color'), btrim(payload->>'storage'),
        btrim(payload->>'ram'), btrim(payload->>'region'),
        btrim(payload->>'condition'), (payload->>'unit_id')::smallint,
        COALESCE((payload->>'reorder_level')::numeric, 0),
        (payload->>'user_id')::integer, (payload->>'user_id')::integer
    ) RETURNING variant_id INTO new_id;
    RETURN new_id;
END;
$$;

CREATE OR REPLACE FUNCTION quantity_update_product(
    p_product_id bigint, payload jsonb
) RETURNS bigint LANGUAGE plpgsql AS $$
BEGIN
    UPDATE products
       SET product_name = COALESCE(
               NULLIF(btrim(payload->>'product_name'), ''), product_name
           ),
           category = COALESCE(
               NULLIF(btrim(payload->>'category'), ''), category
           ),
           description = CASE
               WHEN payload ? 'description'
               THEN NULLIF(btrim(payload->>'description'), '')
               ELSE description
           END,
           is_active = COALESCE((payload->>'is_active')::boolean, is_active),
           updated_by = COALESCE((payload->>'user_id')::integer, updated_by),
           updated_at = CURRENT_TIMESTAMP
     WHERE product_id = p_product_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product not found.'
            USING ERRCODE = 'foreign_key_violation';
    END IF;
    RETURN p_product_id;
END;
$$;

CREATE OR REPLACE FUNCTION quantity_update_variant(
    p_variant_id bigint, payload jsonb
