CREATE TABLE IF NOT EXISTS units_of_measure (
    unit_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(8) NOT NULL UNIQUE,
    unit_name varchar(40) NOT NULL UNIQUE,
    quantity_scale smallint NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT units_of_measure_code_format CHECK (code ~ '^[A-Z]{1,8}$'),
    CONSTRAINT units_of_measure_scale_check CHECK (quantity_scale IN (0, 3))
);

INSERT INTO units_of_measure (code, unit_name, quantity_scale)
VALUES
    ('PCS', 'Piece', 0),
    ('BOX', 'Box', 0),
    ('KG', 'Kilogram', 3),
    ('GM', 'Gram', 3),
    ('LTR', 'Litre', 3),
