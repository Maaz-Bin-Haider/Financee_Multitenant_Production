CREATE TABLE IF NOT EXISTS products (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name varchar(150) NOT NULL,
    category varchar(100) NOT NULL,
    description text,
    is_active boolean NOT NULL DEFAULT true,
    created_by integer,
    updated_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    normalized_name text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(product_name), '\s+', ' ', 'g'))
    ) STORED,
    normalized_category text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(category), '\s+', ' ', 'g'))
    ) STORED,
    CONSTRAINT products_name_check CHECK (btrim(product_name) <> ''),
    CONSTRAINT products_category_check CHECK (btrim(category) <> ''),
    CONSTRAINT products_normalized_unique UNIQUE (
        normalized_name, normalized_category
    )
);

CREATE TABLE IF NOT EXISTS product_variants (
    variant_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products(product_id),
    sku varchar(64) NOT NULL,
    brand varchar(100) NOT NULL,
    model varchar(100) NOT NULL,
    color varchar(100) NOT NULL,
    storage varchar(100) NOT NULL,
    ram varchar(100) NOT NULL,
    region varchar(100) NOT NULL,
    condition varchar(100) NOT NULL,
    unit_id smallint NOT NULL REFERENCES units_of_measure(unit_id),
    reorder_level numeric NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_by integer,
    updated_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    normalized_sku text GENERATED ALWAYS AS (
        upper(regexp_replace(btrim(sku), '\s+', '', 'g'))
    ) STORED,
    normalized_brand text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(brand), '\s+', ' ', 'g'))
    ) STORED,
    normalized_model text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(model), '\s+', ' ', 'g'))
    ) STORED,
    normalized_color text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(color), '\s+', ' ', 'g'))
    ) STORED,
    normalized_storage text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(storage), '\s+', ' ', 'g'))
    ) STORED,
    normalized_ram text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(ram), '\s+', ' ', 'g'))
    ) STORED,
    normalized_region text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(region), '\s+', ' ', 'g'))
    ) STORED,
    normalized_condition text GENERATED ALWAYS AS (
        lower(regexp_replace(btrim(condition), '\s+', ' ', 'g'))
    ) STORED,
    CONSTRAINT product_variants_sku_check CHECK (
        btrim(sku) <> '' AND sku ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$'
    ),
    CONSTRAINT product_variants_dimensions_check CHECK (
        btrim(brand) <> '' AND btrim(model) <> '' AND btrim(color) <> ''
        AND btrim(storage) <> '' AND btrim(ram) <> '' AND btrim(region) <> ''
        AND btrim(condition) <> ''
    ),
    CONSTRAINT product_variants_reorder_check CHECK (
        reorder_level >= 0
        AND reorder_level < 1000000000000000::numeric
        AND reorder_level = round(reorder_level, 3)
    ),
    CONSTRAINT product_variants_sku_unique UNIQUE (normalized_sku),
    CONSTRAINT product_variants_combination_unique UNIQUE (
        product_id, normalized_brand, normalized_model, normalized_color,
        normalized_storage, normalized_ram, normalized_region,
        normalized_condition, unit_id
    )
);

-- Phase 7 prerelease reruns may encounter the earlier numeric(18,3) prototype,
-- whose type coercion rounded a fourth decimal before the trigger could reject
-- it. Store exact numeric input and enforce scale explicitly instead.
DROP TRIGGER IF EXISTS product_variants_precision ON product_variants;
ALTER TABLE product_variants
    ALTER COLUMN reorder_level TYPE numeric USING reorder_level::numeric;
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'product_variants'::regclass
           AND conname = 'product_variants_reorder_precision_check'
    ) THEN
        ALTER TABLE product_variants
            ADD CONSTRAINT product_variants_reorder_precision_check CHECK (
                reorder_level < 1000000000000000::numeric
                AND reorder_level = round(reorder_level, 3)
            );
    END IF;
END;
$$;

