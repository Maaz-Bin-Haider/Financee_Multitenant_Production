CREATE OR REPLACE FUNCTION quantity_finalize_tax_return(
 p_kind text,p_return_id bigint,p_user integer
) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE l record; h record; src record; previous_tax numeric; remaining_tax numeric;
 tax_value numeric; discount_value numeric; tax_total numeric:=0;
 discount_total numeric:=0; counterparty varchar; tax_lines jsonb; j bigint;
BEGIN
 IF p_kind='sale_return' THEN
  PERFORM set_config('financee.sale_return_engine','allowed',true);
  FOR l IN SELECT * FROM sale_return_lines WHERE sale_return_id=p_return_id
   ORDER BY line_number FOR UPDATE LOOP
   SELECT sl.*,si.sale_type,si.payment_account_code INTO src
    FROM sale_lines sl JOIN sale_invoices si USING(sale_invoice_id)
    WHERE sl.sale_line_id=l.source_sale_line_id;
   SELECT COALESCE(sum(rl.tax_reversal_base),0) INTO previous_tax
    FROM sale_return_lines rl JOIN sale_return_invoices ri USING(sale_return_id)
    WHERE rl.source_sale_line_id=src.sale_line_id AND ri.status='posted'
     AND rl.sale_return_id<>p_return_id;
   remaining_tax:=GREATEST(src.tax_base-previous_tax,0);
   tax_value:=CASE WHEN l.quantity=src.quantity-(
    SELECT COALESCE(sum(rl.quantity),0) FROM sale_return_lines rl
    JOIN sale_return_invoices ri USING(sale_return_id)
    WHERE rl.source_sale_line_id=src.sale_line_id AND ri.status='posted'
     AND rl.sale_return_id<>p_return_id)
    THEN remaining_tax ELSE LEAST(remaining_tax,
     round(src.tax_base*l.quantity/src.quantity,2)) END;
   discount_value:=round((src.line_discount_base+src.invoice_discount_base)
    *l.quantity/src.quantity,2);
   UPDATE sale_return_lines SET discount_reversal_base=discount_value,
    taxable_reversal_base=round(src.taxable_base*l.quantity/src.quantity,2),
    tax_reversal_base=tax_value,tax_code_snapshot=src.tax_code_snapshot,
    tax_rate_percent=src.tax_rate_percent,tax_mode=src.tax_mode
    WHERE sale_return_line_id=l.sale_return_line_id;
   tax_total:=tax_total+tax_value; discount_total:=discount_total+discount_value;
  END LOOP;
  SELECT ri.return_date,ri.document_number,
   CASE WHEN si.sale_type='credit' THEN '1200'
    ELSE si.payment_account_code END AS counterparty
   INTO h FROM sale_return_invoices ri JOIN sale_return_lines rl USING(sale_return_id)
   JOIN sale_lines sl ON sl.sale_line_id=rl.source_sale_line_id
   JOIN sale_invoices si USING(sale_invoice_id)
   WHERE ri.sale_return_id=p_return_id LIMIT 1;
  UPDATE sale_return_invoices SET tax_reversal_base=tax_total,
   discount_reversal_base=discount_total WHERE sale_return_id=p_return_id;
  IF tax_total>0 THEN
   SELECT COALESCE(jsonb_agg(jsonb_build_object('account_code',account_code,
    'debit',amount,'credit',0,'description','Output tax reversed')
    ORDER BY account_code),'[]'::jsonb) INTO tax_lines FROM(
    SELECT sl.tax_account_code_snapshot account_code,
     round(sum(rl.tax_reversal_base),4) amount
    FROM sale_return_lines rl JOIN sale_lines sl
     ON sl.sale_line_id=rl.source_sale_line_id
    WHERE rl.sale_return_id=p_return_id GROUP BY sl.tax_account_code_snapshot
   ) grouped WHERE account_code IS NOT NULL;
   tax_lines:=tax_lines||jsonb_build_array(jsonb_build_object(
    'account_code',h.counterparty,'debit',0,'credit',round(tax_total,4),
    'description','Customer tax credit'));
   j:=quantity_post_journal(h.return_date,'Sale-return tax '||h.document_number,
    'sale_return_tax',p_return_id,h.document_number,p_user,tax_lines);
   UPDATE sale_return_invoices SET tax_journal_id=j WHERE sale_return_id=p_return_id;
  END IF;
  PERFORM set_config('financee.sale_return_engine','',true);
 ELSIF p_kind='purchase_return' THEN
  PERFORM set_config('financee.purchase_return_engine','allowed',true);
  FOR l IN SELECT * FROM purchase_return_lines WHERE purchase_return_id=p_return_id
   ORDER BY line_number FOR UPDATE LOOP
   SELECT pl.*,pi.purchase_type,pi.payment_account_code INTO src
    FROM purchase_lines pl JOIN purchase_invoices pi USING(purchase_invoice_id)
    WHERE pl.purchase_line_id=l.source_purchase_line_id;
   SELECT COALESCE(sum(rl.tax_reversal_base),0) INTO previous_tax
    FROM purchase_return_lines rl JOIN purchase_return_invoices ri
     USING(purchase_return_id)
    WHERE rl.source_purchase_line_id=src.purchase_line_id AND ri.status='posted'
     AND rl.purchase_return_id<>p_return_id;
   remaining_tax:=GREATEST(src.tax_base-previous_tax,0);
   tax_value:=CASE WHEN l.quantity=src.quantity-(
    SELECT COALESCE(sum(rl.quantity),0) FROM purchase_return_lines rl
    JOIN purchase_return_invoices ri USING(purchase_return_id)
    WHERE rl.source_purchase_line_id=src.purchase_line_id AND ri.status='posted'
     AND rl.purchase_return_id<>p_return_id)
    THEN remaining_tax ELSE LEAST(remaining_tax,
     round(src.tax_base*l.quantity/src.quantity,2)) END;
   discount_value:=round((src.line_discount_base+src.invoice_discount_base)
    *l.quantity/src.quantity,2);
   UPDATE purchase_return_lines SET discount_reversal_base=discount_value,
    taxable_reversal_base=round(src.taxable_base*l.quantity/src.quantity,2),
    tax_reversal_base=tax_value,tax_code_snapshot=src.tax_code_snapshot,
    tax_rate_percent=src.tax_rate_percent,tax_mode=src.tax_mode
    WHERE purchase_return_line_id=l.purchase_return_line_id;
   tax_total:=tax_total+tax_value;discount_total:=discount_total+discount_value;
  END LOOP;
  SELECT ri.return_date,ri.document_number,
   CASE WHEN pi.purchase_type='credit' THEN '2000'
    ELSE pi.payment_account_code END AS counterparty
   INTO h FROM purchase_return_invoices ri JOIN purchase_return_lines rl
    USING(purchase_return_id) JOIN purchase_lines pl
    ON pl.purchase_line_id=rl.source_purchase_line_id
   JOIN purchase_invoices pi USING(purchase_invoice_id)
   WHERE ri.purchase_return_id=p_return_id LIMIT 1;
  UPDATE purchase_return_invoices SET tax_reversal_base=tax_total,
   discount_reversal_base=discount_total WHERE purchase_return_id=p_return_id;
  IF tax_total>0 THEN
   tax_lines:=jsonb_build_array(jsonb_build_object('account_code',h.counterparty,
    'debit',round(tax_total,4),'credit',0,'description','Vendor tax credit'));
   SELECT tax_lines||COALESCE(jsonb_agg(jsonb_build_object(
    'account_code',account_code,'debit',0,'credit',amount,
    'description','Input tax reversed') ORDER BY account_code),'[]'::jsonb)
    INTO tax_lines FROM(SELECT pl.tax_account_code_snapshot account_code,
     round(sum(rl.tax_reversal_base),4) amount FROM purchase_return_lines rl
     JOIN purchase_lines pl ON pl.purchase_line_id=rl.source_purchase_line_id
     WHERE rl.purchase_return_id=p_return_id
     GROUP BY pl.tax_account_code_snapshot) grouped WHERE account_code IS NOT NULL;
   j:=quantity_post_journal(h.return_date,'Purchase-return tax '||h.document_number,
    'purchase_return_tax',p_return_id,h.document_number,p_user,tax_lines);
   UPDATE purchase_return_invoices SET tax_journal_id=j
    WHERE purchase_return_id=p_return_id;
  END IF;
  PERFORM set_config('financee.purchase_return_engine','',true);
 ELSE RAISE EXCEPTION 'Invalid return kind.' USING ERRCODE='check_violation';
 END IF;
 RETURN jsonb_build_object('tax_journal_id',j,'tax_reversal_base',tax_total,
  'discount_reversal_base',discount_total);
END;
$$;

