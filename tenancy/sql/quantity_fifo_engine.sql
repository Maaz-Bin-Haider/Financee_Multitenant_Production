-- Idempotent Phase 9 movement/FIFO engine for QUANTITY schemas, version 5.
DO $$
BEGIN
    IF to_regclass('tenant_schema_metadata') IS NULL
       OR NOT EXISTS (
           SELECT 1 FROM tenant_schema_metadata
            WHERE id = true AND family = 'quantity' AND version >= 4
       ) THEN
        RAISE EXCEPTION 'Quantity FIFO rollout refused: family/version mismatch.';
    END IF;
END;
$$;

CREATE SEQUENCE IF NOT EXISTS inventory_effective_sequence_seq AS bigint;

CREATE TABLE IF NOT EXISTS stock_movements (
    movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id bigint NOT NULL REFERENCES product_variants(variant_id),
    warehouse_id bigint NOT NULL REFERENCES warehouses(warehouse_id),
    movement_date date NOT NULL,
    effective_sequence bigint NOT NULL
        DEFAULT nextval('inventory_effective_sequence_seq'),
    movement_type varchar(24) NOT NULL,
    quantity_in numeric NOT NULL DEFAULT 0,
    quantity_out numeric NOT NULL DEFAULT 0,
    source_type varchar(32) NOT NULL,
    source_id bigint NOT NULL,
    source_line_id bigint NOT NULL,
    document_number varchar(32),
    unit_cost_base numeric(20,6),
    total_cost_base numeric(24,6),
    description text,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reversal_of_movement_id bigint REFERENCES stock_movements(movement_id),
    CONSTRAINT stock_movements_direction_check CHECK (
        (quantity_in > 0 AND quantity_out = 0)
        OR (quantity_out > 0 AND quantity_in = 0)
    ),
    CONSTRAINT stock_movements_three_decimal_check CHECK (
        quantity_in = round(quantity_in, 3)
        AND quantity_out = round(quantity_out, 3)
        AND quantity_in < 1000000000000000::numeric
        AND quantity_out < 1000000000000000::numeric
    ),
    CONSTRAINT stock_movements_type_check CHECK (
        movement_type IN (
            'opening', 'purchase', 'sale', 'sale_return',
            'purchase_return', 'transfer_out', 'transfer_in',
            'adjustment_in', 'adjustment_out', 'reversal_in', 'reversal_out'
        )
    ),
    CONSTRAINT stock_movements_source_check CHECK (
        source_type ~ '^[a-z][a-z0-9_]{1,31}$'
    ),
    CONSTRAINT stock_movements_cost_check CHECK (
        unit_cost_base IS NULL OR unit_cost_base >= 0
    ),
    CONSTRAINT stock_movements_reversal_check CHECK (
        reversal_of_movement_id IS NULL
        OR reversal_of_movement_id <> movement_id
    ),
    CONSTRAINT stock_movements_source_unique UNIQUE (
        source_type, source_id, source_line_id, movement_type
    ),
    CONSTRAINT stock_movements_effective_unique UNIQUE (
        variant_id, warehouse_id, movement_date, effective_sequence
    ),
    CONSTRAINT stock_movements_one_reversal UNIQUE (reversal_of_movement_id)
);

CREATE INDEX IF NOT EXISTS stock_movements_scope_order_idx
    ON stock_movements(
        warehouse_id, variant_id, movement_date, effective_sequence, movement_id
    );

CREATE TABLE IF NOT EXISTS stock_balances (
    variant_id bigint NOT NULL REFERENCES product_variants(variant_id),
    warehouse_id bigint NOT NULL REFERENCES warehouses(warehouse_id),
    on_hand_quantity numeric NOT NULL DEFAULT 0,
    balance_version bigint NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (variant_id, warehouse_id),
    CONSTRAINT stock_balances_non_negative CHECK (on_hand_quantity >= 0),
    CONSTRAINT stock_balances_precision CHECK (
        on_hand_quantity = round(on_hand_quantity, 3)
        AND on_hand_quantity < 1000000000000000::numeric
    )
);

CREATE TABLE IF NOT EXISTS fifo_layers (
    layer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inbound_movement_id bigint NOT NULL UNIQUE
        REFERENCES stock_movements(movement_id),
    variant_id bigint NOT NULL REFERENCES product_variants(variant_id),
    warehouse_id bigint NOT NULL REFERENCES warehouses(warehouse_id),
    source_type varchar(32) NOT NULL,
    source_id bigint NOT NULL,
    source_line_id bigint NOT NULL,
    source_date date NOT NULL,
    effective_sequence bigint NOT NULL,
    original_quantity numeric NOT NULL,
    remaining_quantity numeric NOT NULL,
    unit_cost_base numeric(20,6) NOT NULL,
    restored_from_allocation_id bigint,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fifo_layers_quantity_check CHECK (
        original_quantity > 0
        AND original_quantity = round(original_quantity, 3)
        AND remaining_quantity >= 0
        AND remaining_quantity <= original_quantity
        AND remaining_quantity = round(remaining_quantity, 3)
    ),
    CONSTRAINT fifo_layers_cost_check CHECK (unit_cost_base >= 0)
);

CREATE INDEX IF NOT EXISTS fifo_layers_available_idx
    ON fifo_layers(
        warehouse_id, variant_id, source_date, effective_sequence, layer_id
    ) WHERE remaining_quantity > 0;

CREATE TABLE IF NOT EXISTS fifo_allocations (
    allocation_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outbound_movement_id bigint NOT NULL
        REFERENCES stock_movements(movement_id),
    layer_id bigint NOT NULL REFERENCES fifo_layers(layer_id),
    quantity numeric NOT NULL,
    unit_cost_base numeric(20,6) NOT NULL,
    total_cost_base numeric(24,6) NOT NULL,
    allocation_order integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fifo_allocations_quantity_check CHECK (
        quantity > 0 AND quantity = round(quantity, 3)
    ),
    CONSTRAINT fifo_allocations_cost_check CHECK (
        unit_cost_base >= 0 AND total_cost_base >= 0
    ),
    CONSTRAINT fifo_allocations_order_check CHECK (allocation_order > 0),
    CONSTRAINT fifo_allocations_layer_unique UNIQUE (
        outbound_movement_id, layer_id
    ),
    CONSTRAINT fifo_allocations_order_unique UNIQUE (
        outbound_movement_id, allocation_order
    )
);

CREATE INDEX IF NOT EXISTS fifo_allocations_layer_idx
    ON fifo_allocations(layer_id);

CREATE OR REPLACE FUNCTION quantity_inventory_write_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF current_setting('financee.inventory_engine', true) = 'allowed' THEN
        IF TG_OP = 'DELETE' THEN
            RETURN OLD;
        END IF;
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'Inventory history is writable only through controlled functions.'
        USING ERRCODE = 'insufficient_privilege';
END;
$$;

DROP TRIGGER IF EXISTS stock_movements_write_guard ON stock_movements;
CREATE TRIGGER stock_movements_write_guard
BEFORE INSERT OR UPDATE OR DELETE ON stock_movements
FOR EACH ROW EXECUTE FUNCTION quantity_inventory_write_guard();

