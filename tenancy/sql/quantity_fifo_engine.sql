CREATE TRIGGER fifo_allocations_write_guard
BEFORE INSERT OR UPDATE OR DELETE ON fifo_allocations
FOR EACH ROW EXECUTE FUNCTION quantity_inventory_write_guard();

DROP TRIGGER IF EXISTS stock_balances_write_guard ON stock_balances;
