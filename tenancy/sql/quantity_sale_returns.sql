CREATE OR REPLACE FUNCTION quantity_guard_sale_with_returns()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status='posted' AND NEW.status<>OLD.status AND EXISTS (
        SELECT 1 FROM sale_return_lines rl
        JOIN sale_return_invoices r USING(sale_return_id)
        WHERE rl.source_sale_line_id IN (
            SELECT sale_line_id FROM sale_lines
             WHERE sale_invoice_id=OLD.sale_invoice_id
        ) AND r.status='posted'
    ) THEN
        RAISE EXCEPTION 'Sale cannot be changed after a posted return.'
            USING ERRCODE='check_violation';
    END IF;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS sale_invoices_return_guard ON sale_invoices;
CREATE TRIGGER sale_invoices_return_guard BEFORE UPDATE ON sale_invoices
FOR EACH ROW EXECUTE FUNCTION quantity_guard_sale_with_returns();

