CREATE OR REPLACE FUNCTION quantity_protect_sale_return()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF current_setting('financee.sale_return_engine',true)='allowed' THEN
        RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
    END IF;
    RAISE EXCEPTION 'Posted sale-return records are immutable; use return operations.'
        USING ERRCODE='check_violation';
END;
$$;

