CREATE TABLE IF NOT EXISTS sale_return_invoices (
    sale_return_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_number varchar(32) NOT NULL UNIQUE,
    return_date date NOT NULL,
    customer_name varchar(200) NOT NULL,
    description text,
    status varchar(10) NOT NULL DEFAULT 'draft',
    revision_number integer NOT NULL DEFAULT 1,
    revenue_total_base numeric(24,6) NOT NULL DEFAULT 0,
    cogs_total_base numeric(24,6) NOT NULL DEFAULT 0,
    journal_id bigint UNIQUE REFERENCES journal_entries(journal_id),
    reversal_journal_id bigint UNIQUE REFERENCES journal_entries(journal_id),
    idempotency_key varchar(100) NOT NULL UNIQUE,
    request_fingerprint varchar(32) NOT NULL,
    created_by integer, updated_by integer, reversed_by integer,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reversed_at timestamptz,
    CONSTRAINT sale_return_customer_required CHECK (btrim(customer_name)<>''),
    CONSTRAINT sale_return_status_check CHECK (status IN ('draft','posted','reversed')),
    CONSTRAINT sale_return_totals_check CHECK (
        revenue_total_base>=0 AND cogs_total_base>=0
    )
);

CREATE TABLE IF NOT EXISTS sale_return_lines (
    sale_return_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_return_id bigint NOT NULL REFERENCES sale_return_invoices(sale_return_id),
    line_number integer NOT NULL,
    source_sale_line_id bigint NOT NULL REFERENCES sale_lines(sale_line_id),
    variant_id bigint NOT NULL REFERENCES product_variants(variant_id),
    source_warehouse_id bigint NOT NULL REFERENCES warehouses(warehouse_id),
    destination_warehouse_id bigint NOT NULL REFERENCES warehouses(warehouse_id),
    quantity numeric NOT NULL,
    unit_price_base numeric(20,6) NOT NULL,
    revenue_total_base numeric(24,6) NOT NULL,
    cogs_total_base numeric(24,6) NOT NULL,
    description text,
    CONSTRAINT sale_return_line_quantity CHECK (
        quantity>0 AND quantity=round(quantity,3)
    ),
    CONSTRAINT sale_return_line_values CHECK (
        unit_price_base>0
        AND revenue_total_base=round(quantity*unit_price_base,6)
        AND cogs_total_base>=0
    ),
    CONSTRAINT sale_return_line_number_unique UNIQUE(sale_return_id,line_number),
    CONSTRAINT sale_return_source_unique UNIQUE(sale_return_id,source_sale_line_id)
);

CREATE TABLE IF NOT EXISTS sale_return_cost_restorations (
    restoration_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_return_line_id bigint NOT NULL
        REFERENCES sale_return_lines(sale_return_line_id),
    -- Snapshot lineage ID. FIFO replay rebuilds allocation rows, so this
    -- historical identifier cannot safely retain a live foreign key.
    source_allocation_id bigint NOT NULL,
    quantity numeric NOT NULL,
    unit_cost_base numeric(20,6) NOT NULL,
    total_cost_base numeric(24,6) NOT NULL,
    movement_id bigint NOT NULL UNIQUE REFERENCES stock_movements(movement_id),
    restoration_order integer NOT NULL,
    CONSTRAINT sale_return_restoration_quantity CHECK (
        quantity>0 AND quantity=round(quantity,3)
    ),
    CONSTRAINT sale_return_restoration_value CHECK (
        unit_cost_base>=0
        AND total_cost_base=round(quantity*unit_cost_base,6)
    ),
    CONSTRAINT sale_return_restoration_order_unique
        UNIQUE(sale_return_line_id,restoration_order)
);
ALTER TABLE sale_return_cost_restorations
