CREATE TABLE IF NOT EXISTS chart_of_accounts (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_code varchar(20) NOT NULL UNIQUE,
    account_name varchar(150) NOT NULL UNIQUE,
    account_type varchar(20) NOT NULL,
    normal_balance varchar(6) NOT NULL,
    is_system boolean NOT NULL DEFAULT true,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chart_of_accounts_code_format CHECK (
        account_code ~ '^[A-Z0-9][A-Z0-9.-]{0,19}$'
    ),
    CONSTRAINT chart_of_accounts_type_check CHECK (
        account_type IN ('Asset', 'Liability', 'Equity', 'Revenue', 'Expense')
    ),
    CONSTRAINT chart_of_accounts_normal_balance_check CHECK (
        normal_balance IN ('Debit', 'Credit')
    ),
    CONSTRAINT chart_of_accounts_type_balance_check CHECK (
        (account_type IN ('Asset', 'Expense') AND normal_balance = 'Debit')
        OR (account_type IN ('Liability', 'Equity', 'Revenue')
            AND normal_balance = 'Credit')
    )
);

